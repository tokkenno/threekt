/**
 * Tessellates Martin Newell's Utah teapot using the patch order of Three.js.
 * [size] is half the height and [segments] is clamped to at least two.
 * [fitLid] expands the lid horizontally and disabling [blinn] restores the original proportions.
 * Threekt takes an integer subdivision count and evaluates the Bézier basis and its derivatives
 * directly instead of multiplying the control point matrices.
 */
@JsExport
class TeapotGeometry(
    size: Double = 50.0,
    segments: Int = 10,
    bottom: Boolean = true,
    lid: Boolean = true,
    body: Boolean = true,
    fitLid: Boolean = true,
    blinn: Boolean = true,
) : BufferGeometry() {
    init {
        val divisions = maxOf(2, segments)
        val row = divisions + 1
        val patchCount = (if (body) 20 else 0) + (if (lid) 8 else 0) + (if (bottom) 4 else 0)
        val vertexCount = patchCount * row * row
        val positions = FloatArray(vertexCount * 3)
        val normals = FloatArray(positions.size)
        val uvs = FloatArray(vertexCount * 2)
        val indices = IntArray(patchCount * divisions * divisions * 6)
        val heightScale = if (blinn) 1.0 else 1.3
        val middle = 3.15 * heightScale / 2
        val trueSize = size / middle
        val bases = Array(row) { bezier(it.toDouble() / divisions) }
        val normal = Vector3()
        val point = Vector3()
        val ds = Vector3()
        val dt = Vector3()
        var vertex = 0
        var index = 0

        fun samePosition(first: Int, second: Int): Boolean {
            val a = first * 3
            val b = second * 3
            return positions[a] == positions[b] && positions[a + 1] == positions[b + 1] &&
                positions[a + 2] == positions[b + 2]
        }

        fun addFace(a: Int, b: Int, c: Int) {
            if (samePosition(a, b) || samePosition(b, c) || samePosition(c, a)) return
            indices[index++] = a
            indices[index++] = b
            indices[index++] = c
        }

        for (patch in 0 until 32) {
            val usePatch = when (patch) {
                in 0..19 -> body
                in 20..27 -> lid
                else -> bottom
            }
            if (!usePatch) continue
            val lidScale = if (fitLid && patch in 20..27) 1.077 else 1.0
            val controls = Array(16) { i ->
                val k = teapotPatches[patch * 16 + i] * 3
                Vector3(teapotVertices[k] * lidScale, teapotVertices[k + 1] * lidScale, teapotVertices[k + 2] * heightScale)
            }
            val start = vertex
            for (s in 0 until row) {
                val (sWeights, sDerivative) = bases[s]
                for (t in 0 until row) {
                    val (tWeights, tDerivative) = bases[t]
                    point.set(0.0, 0.0, 0.0)
                    ds.set(0.0, 0.0, 0.0)
                    dt.set(0.0, 0.0, 0.0)
                    for (i in 0..3) for (j in 0..3) {
                        val control = controls[i * 4 + j]
                        point.addScaledVector(control, sWeights[i] * tWeights[j])
                        ds.addScaledVector(control, sDerivative[i] * tWeights[j])
                        dt.addScaledVector(control, sWeights[i] * tDerivative[j])
                    }
                    if (abs(point.x) < 1e-12 && abs(point.y) < 1e-12) {
                        point.x = 0.0
                        point.y = 0.0
                        normal.set(0.0, 0.0, if (point.z > middle) 1.0 else -1.0)
                    } else {
                        normal.crossVectors(dt, ds).normalize()
                    }
                    val i = vertex * 3
                    positions[i] = (point.x * trueSize).toFloat()
                    positions[i + 1] = ((point.z - middle) * trueSize).toFloat()
                    positions[i + 2] = (-point.y * trueSize).toFloat()
                    normals[i] = normal.x.toFloat()
                    normals[i + 1] = normal.z.toFloat()
                    normals[i + 2] = -normal.y.toFloat()
                    uvs[vertex * 2] = 1f - t.toFloat() / divisions
                    uvs[vertex * 2 + 1] = 1f - s.toFloat() / divisions
                    vertex++
                }
            }
            for (s in 0 until divisions) for (t in 0 until divisions) {
                val a = start + s * row + t
                addFace(a, a + 1, a + row + 1)
                addFace(a, a + row + 1, a + row)
            }
        }

        setIndex(indices.copyOf(index))
        setAttribute("position", Float32BufferAttribute(positions, 3))
        setAttribute("normal", Float32BufferAttribute(normals, 3))
        setAttribute("uv", Float32BufferAttribute(uvs, 2))
        computeBoundingSphere()
    }

    private fun bezier(t: Double): Pair<DoubleArray, DoubleArray> {
        val u = 1 - t
        return doubleArrayOf(u * u * u, 3 * t * u * u, 3 * t * t * u, t * t * t) to
            doubleArrayOf(-3 * u * u, 3 * u * (1 - 3 * t), 3 * t * (2 - 3 * t), 3 * t * t)
    }

